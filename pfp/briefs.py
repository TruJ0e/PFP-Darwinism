"""
v0.47: Evolving Exploration Briefs (Truman's Design).

1. MODEL-GENERATED BRIEFS:
   Each branch works under an exploration brief: a short prompt derived from
   the main problem that assigns it a region of the hypothesis space to explore.
   Briefs are generated by a model at runtime. Absolutely no problem-specific
   hardcoding in prompts, code, or tests.

2. COVERAGE BY CONSTRUCTION:
   Briefs are generated against each other: each new brief is produced with
   the already-generated set in view, instructed to cover what has not been
   covered. The final brief in a set is explicitly forced toward
   "what is nobody looking at?"

3. BRIEFS MUTATE:
   Descendants receive revised briefs:
   (a) children spawned at a fork get brief variations against the parent's
       brief and their siblings';
   (b) when a branch survives a falsification carrying an objection, the
       objection feeds its descendants' briefs (explore around what the attack exposed).

4. SELECTION ACTS ON FRAMINGS:
   Brief lineage is journaled (spawn events carry brief, brief_id, and parent_brief_id)
   so the proof trail shows which framings produced survivors and which died.

v0.47.1 — briefs FAIL CLOSED:
   Brief calls go to reasoning models, so they get reasoning-class completion budgets
   (BRIEF_MAX_TOKENS, retry at BRIEF_RETRY_MAX_TOKENS); a 200-token budget is eaten by
   reasoning and returns empty content. A brief is only ever the model's parsed JSON
   `brief` field after validation — never raw output, never synthesized boilerplate.
   Every failed attempt is reported through `on_failure` (the harness journals it as a
   `brief_generation_failed` event). After one retry a starter proceeds with NO brief
   and an objection revision keeps the current brief.

v0.47.1 amendment — divergence at EVERY spawn (Truman):
   A descendant inherits the MAP (what the lineage covered, what died, which objections
   landed), never the ROUTE. The fork-mutation call sees the parent's brief, its
   conclusion / surviving claims, the falsifier objections it carries, the routes its
   ancestors already excluded, and the sibling briefs already generated at this fork, and
   must assign a route none of them took. A reply that restates the parent's or a
   sibling's brief is rejected like any other invalid reply. If mutation still fails after
   the retry the child proceeds with NO brief: the parent's brief reaches it only as an
   excluded route (covered ground), never as its own assignment.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from typing import Any, Callable, Dict, List, Optional, Sequence, Tuple

from .jsonutil import parse_json_object


def compute_brief_id(brief_text: str) -> str:
    """Content-addressed identity for an exploration brief."""
    cleaned = " ".join(brief_text.strip().split())
    digest = hashlib.sha256(cleaned.encode("utf-8")).hexdigest()[:12]
    return f"brief_{digest}"


@dataclass
class ExplorationBrief:
    """
    An evolving exploration brief assigned to a branch (v0.47).
    - brief_id: Content-addressed unique identifier for this framing
    - brief: Concise hypothesis space framing (1-2 sentences)
    - parent_brief_id: The brief_id of the ancestor brief this evolved from
    - trigger: Event that generated this brief ("starter", "fork_variation", "falsification_objection")
    - depth: Generational depth of this brief framing
    """

    brief_id: str
    brief: str
    parent_brief_id: Optional[str] = None
    trigger: str = "starter"
    depth: int = 0

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {
            "brief_id": self.brief_id,
            "brief": self.brief,
            "trigger": self.trigger,
            "depth": self.depth,
        }
        if self.parent_brief_id is not None:
            d["parent_brief_id"] = self.parent_brief_id
        return d


# Reasoning-class completion budgets (v0.47.1): the v0.37+ conclusion/judge class.
BRIEF_MAX_TOKENS = 768
BRIEF_RETRY_MAX_TOKENS = 1024
# A brief is 1-2 sentences; anything longer is clipped at a word boundary.
MAX_BRIEF_CHARS = 600
# Journal event type for a failed brief call (one per failed attempt).
BRIEF_FAILURE_EVENT = "brief_generation_failed"
# Probe/fork payload keys: a brief carrying any of these is a leaked payload, not a framing.
_PAYLOAD_MARKERS = ('"fork_id"', '"approach"', '"reasoning"', '"conclusion"', '"support_score"', '"fork_description"')

BriefFailureSink = Callable[[Dict[str, Any]], None]
# Extra rejection rule for an otherwise valid brief: returns a failure reason, or "" to accept.
BriefRejector = Callable[[str], str]


def _norm_brief(text: str) -> str:
    return " ".join(str(text).split()).casefold()


def validate_brief_text(text: Any) -> Tuple[Optional[str], str]:
    """
    Validate a candidate brief. Returns (clean_text, "") or (None, reason).
    Rejects empty text and probe-shaped payloads; clips over-long briefs.
    """
    if not isinstance(text, str):
        return None, "brief_not_string"
    cleaned = " ".join(text.strip().split())
    if not cleaned:
        return None, "empty_brief"
    if cleaned[0] in "{[" or cleaned.startswith("```"):
        return None, "payload_shaped_brief"
    lowered = cleaned.lower()
    if any(m in lowered for m in _PAYLOAD_MARKERS):
        return None, "payload_markers_in_brief"
    if len(cleaned) > MAX_BRIEF_CHARS:
        clipped = cleaned[:MAX_BRIEF_CHARS].rsplit(" ", 1)[0].rstrip(" ,;:")
        cleaned = clipped or cleaned[:MAX_BRIEF_CHARS]
    return cleaned, ""


def _parse_brief_reply(raw: str) -> Tuple[Optional[str], str]:
    """The brief is the parsed JSON `brief` field, validated — else prose fallback (v0.52).

    A reasoning model that burns its budget mid-JSON used to kill divergence
    outright (run 13: fork-mutation failures on truncated output). If the reply
    does not parse but carries a readable prose sentence, that sentence is the
    brief. JSON-shaped fragments never fall back: anything containing braces or
    quotes stays a failure, so a truncated payload cannot become a brief.
    """
    if not raw.strip():
        return None, "empty_content"
    parsed = parse_json_object(raw)
    if parsed and "brief" in parsed:
        return validate_brief_text(parsed.get("brief"))
    text = re.sub(r"<think>.*?</think>", "", raw, flags=re.S)
    text = re.sub(r"```(?:json)?(.*?)```", r"\1", text, flags=re.S)
    text = " ".join(text.split())
    if text and not any(c in text for c in "{}\"" ):
        sentences = re.split(r"(?<=[.!?])\s+", text)
        candidate = " ".join(sentences[:2])[:300].strip()
        if candidate:
            brief_text, _ = validate_brief_text(candidate)
            if brief_text is not None:
                return brief_text, ""
    if not parsed:
        return None, "unparseable_json"
    return None, "missing_brief_field"


def _request_brief(
    client: Any,
    prompt: str,
    temperature: float,
    model: Optional[str],
    max_tokens: int,
    retry_max_tokens: int,
    context: Dict[str, Any],
    on_failure: Optional[BriefFailureSink],
    reject: Optional[BriefRejector] = None,
) -> Tuple[Optional[str], float]:
    """
    One brief call, retried ONCE at the larger budget on empty/unparseable/invalid output.
    Every failed attempt is reported to `on_failure`. Returns (brief_text or None, total cost).
    """
    total_cost = 0.0
    budgets = [int(max_tokens), int(max(retry_max_tokens, max_tokens))]
    for attempt, budget in enumerate(budgets, start=1):
        kwargs: Dict[str, Any] = {"temperature": temperature, "max_tokens": budget}
        if model:
            kwargs["model"] = model
        resp = client.chat.completions.create(
            messages=[{"role": "user", "content": prompt}],
            **kwargs,
        )
        total_cost += float(getattr(getattr(resp, "usage", None), "cost_usd", 0.0) or 0.0)
        raw = (resp.choices[0].message.content if resp.choices else "") or ""
        text, reason = _parse_brief_reply(raw)
        if text is not None and reject is not None:
            reason = reject(text)
            if reason:
                text = None
        if text is not None:
            return text, total_cost
        if on_failure is not None:
            failure = dict(context)
            failure.update(
                {
                    "attempt": attempt,
                    "attempts_allowed": len(budgets),
                    "max_tokens": budget,
                    "reason": reason,
                    "raw_chars": len(raw),
                    "will_retry": attempt < len(budgets),
                }
            )
            on_failure(failure)
    return None, total_cost


def generate_starter_briefs(
    client: Any,
    problem: str,
    count: int,
    model: Optional[str] = None,
    max_tokens: int = BRIEF_MAX_TOKENS,
    retry_max_tokens: int = BRIEF_RETRY_MAX_TOKENS,
    on_failure: Optional[BriefFailureSink] = None,
) -> tuple[List[Optional[ExplorationBrief]], List[float]]:
    """
    Generate starter exploration briefs with Coverage by Construction (v0.47).
    Each brief is generated with all previously generated briefs in view, instructed
    to cover what has not been covered. The final brief is forced toward
    'what is nobody looking at?'

    Fails closed (v0.47.1): a slot whose call stays empty/unparseable/invalid after one
    retry is None — that starter runs with no brief. Failures go to `on_failure`.
    """
    if count <= 0:
        return [], []

    briefs: List[Optional[ExplorationBrief]] = []
    costs: List[float] = []

    for idx in range(count):
        is_final = (idx == count - 1 and count > 1)
        generated = [b for b in briefs if b is not None]
        prior_texts = [f"- Brief {i + 1} [{b.brief_id}]: {b.brief}" for i, b in enumerate(generated)]
        priors_block = "\n".join(prior_texts) if prior_texts else "None (initial brief in population)."

        if is_final:
            diversity_clause = (
                "FINAL BRIEF MANDATE: You are the final brief in this starter population. "
                "You are explicitly obligated to explore what nobody is looking at: "
                "investigate an unconventional, orthogonal, or overlooked hypothesis space region "
                "that challenges common assumptions."
            )
        else:
            diversity_clause = (
                "Obligation: Diversity by construction. You MUST assign a distinct region of the "
                "hypothesis space that does not duplicate or overlap with the prior briefs above."
            )

        prompt = (
            f"generate_exploration_brief starter index={idx + 1} of {count}\n"
            f"Problem: {problem}\n"
            f"Prior exploration briefs assigned in this population:\n"
            f"{priors_block}\n"
            f"{diversity_clause}\n"
            "Assign this branch a concise exploration brief in 1-2 sentences. "
            'Return JSON: {"brief": "...", "focus_area": "..."}'
        )

        brief_text, cost = _request_brief(
            client,
            prompt,
            temperature=0.7,
            model=model,
            max_tokens=max_tokens,
            retry_max_tokens=retry_max_tokens,
            context={"stage": "starter", "starter_index": idx, "outcome_on_failure": "no_brief"},
            on_failure=on_failure,
        )
        costs.append(cost)
        if brief_text is None:
            briefs.append(None)
            continue

        b_id = compute_brief_id(brief_text)
        briefs.append(
            ExplorationBrief(
                brief_id=b_id,
                brief=brief_text,
                parent_brief_id=None,
                trigger="starter",
                depth=0,
            )
        )

    return briefs, costs


def mutate_brief_for_fork(
    client: Any,
    problem: str,
    parent_brief: ExplorationBrief,
    fork_description: str,
    fork_reasoning: str,
    prior_sibling_briefs: Sequence[ExplorationBrief] = (),
    survived_objection: str = "",
    is_final: bool = False,
    depth: int = 1,
    model: Optional[str] = None,
    max_tokens: int = BRIEF_MAX_TOKENS,
    retry_max_tokens: int = BRIEF_RETRY_MAX_TOKENS,
    on_failure: Optional[BriefFailureSink] = None,
    parent_conclusion: str = "",
    parent_objections: Sequence[str] = (),
    excluded_routes: Sequence[str] = (),
) -> tuple[Optional[ExplorationBrief], float]:
    """
    Mutate an exploration brief for a child branch at a fork (v0.47).

    Divergence obligation (v0.47.1): the call sees the lineage MAP — the parent's brief,
    its conclusion / surviving claims, the falsifier objections it carries, routes already
    excluded upstream, and the sibling briefs generated so far at this fork — and must
    assign a route the parent did NOT take and no sibling is taking (coverage by
    construction, applied recursively). A reply restating the parent's, a sibling's, or an
    excluded brief is rejected and retried once like any other invalid reply.

    Returns (None, cost) when mutation still fails after the retry: the caller spawns the
    child brief-less, carrying the parent's brief only as an excluded route.
    """
    prior_texts = [f"- Sibling [{b.brief_id}]: {b.brief}" for b in prior_sibling_briefs]
    priors_block = "\n".join(prior_texts) if prior_texts else "None (first sibling in this cohort)."

    objections = [" ".join(str(o).split()) for o in (survived_objection, *parent_objections) if str(o or "").strip()]
    objections = list(dict.fromkeys(objections))
    objection_block = (
        "Falsification objections carried by parent:\n"
        + "\n".join(f"- {o}" for o in objections)
        + "\nExplore around what these attacks exposed.\n"
        if objections
        else ""
    )
    excluded = list(dict.fromkeys(" ".join(str(r).split()) for r in excluded_routes if str(r or "").strip()))
    excluded_block = (
        "Routes already covered upstream in this lineage (do not repeat):\n"
        + "\n".join(f"- {r}" for r in excluded)
        + "\n"
        if excluded
        else ""
    )
    claims = " ".join(str(parent_conclusion or "").split())
    claims_line = f"Parent conclusion / surviving claims: {claims}\n" if claims else ""

    if is_final and len(prior_sibling_briefs) > 0:
        sibling_clause = (
            "MANDATE FOR FINAL SIBLING: Force this brief toward an orthogonal angle or overlooked mechanism "
            "not covered by the parent or the sibling briefs in this cohort."
        )
    else:
        sibling_clause = (
            "Ensure this brief specializes toward this fork's approach while remaining distinct from siblings."
        )

    trigger = "falsification_objection" if objections else "fork_variation"
    prompt = (
        f"mutate_exploration_brief {trigger} depth={depth}\n"
        f"Problem: {problem}\n"
        f"Parent brief [{parent_brief.brief_id}] (route already taken by the parent): {parent_brief.brief}\n"
        f"{claims_line}"
        f"{objection_block}"
        f"{excluded_block}"
        f"Fork under exploration: {fork_description}\n"
        f"Reasoning step: {fork_reasoning}\n"
        f"Prior sibling briefs in this fork cohort:\n"
        f"{priors_block}\n"
        "Divergence obligation: assign a route the parent did NOT take and the siblings above are not "
        "taking. Do not restate the parent's brief or a sibling's brief.\n"
        f"{sibling_clause}\n"
        "State this descendant branch's mutated exploration brief in 1-2 sentences. "
        'Return JSON: {"brief": "...", "focus_area": "..."}'
    )

    taken = {_norm_brief(parent_brief.brief): "duplicates_parent_brief"}
    for b in prior_sibling_briefs:
        taken.setdefault(_norm_brief(b.brief), "duplicates_sibling_brief")
    for r in excluded:
        taken.setdefault(_norm_brief(r), "duplicates_excluded_route")

    brief_text, cost = _request_brief(
        client,
        prompt,
        temperature=0.7,
        model=model,
        max_tokens=max_tokens,
        retry_max_tokens=retry_max_tokens,
        context={
            "stage": "fork_mutation",
            "parent_brief_id": parent_brief.brief_id,
            "fork": str(fork_description)[:200],
            "sibling_index": len(prior_sibling_briefs),
            "outcome_on_failure": "briefless_parent_route_excluded",
        },
        on_failure=on_failure,
        reject=lambda text: taken.get(_norm_brief(text), ""),
    )
    if brief_text is None:
        return None, cost

    b_id = compute_brief_id(brief_text)
    child_brief = ExplorationBrief(
        brief_id=b_id,
        brief=brief_text,
        parent_brief_id=parent_brief.brief_id,
        trigger=trigger,
        depth=depth,
    )
    return child_brief, cost


def revise_brief_for_objection(
    client: Any,
    problem: str,
    current_brief: ExplorationBrief,
    objection: str,
    depth: int = 0,
    model: Optional[str] = None,
    max_tokens: int = BRIEF_MAX_TOKENS,
    retry_max_tokens: int = BRIEF_RETRY_MAX_TOKENS,
    on_failure: Optional[BriefFailureSink] = None,
) -> tuple[ExplorationBrief, float]:
    """
    Revise a brief when a branch survives a falsification carrying an objection (v0.47).
    A revision that still fails after one retry keeps the current brief unchanged (v0.47.1).
    """
    prompt = (
        f"mutate_exploration_brief falsification_objection depth={depth}\n"
        f"Problem: {problem}\n"
        f"Current brief [{current_brief.brief_id}]: {current_brief.brief}\n"
        f"Survived falsification objection: {objection}\n"
        "Revise this exploration brief to incorporate what the falsification attack exposed. "
        "The revised brief must investigate hypotheses that test or resolve this vulnerability. "
        'Return JSON: {"brief": "...", "focus_area": "..."}'
    )

    brief_text, cost = _request_brief(
        client,
        prompt,
        temperature=0.5,
        model=model,
        max_tokens=max_tokens,
        retry_max_tokens=retry_max_tokens,
        context={
            "stage": "objection_revision",
            "parent_brief_id": current_brief.brief_id,
            "outcome_on_failure": "kept_current_brief",
        },
        on_failure=on_failure,
    )
    if brief_text is None:
        return current_brief, cost

    b_id = compute_brief_id(brief_text)
    revised = ExplorationBrief(
        brief_id=b_id,
        brief=brief_text,
        parent_brief_id=current_brief.brief_id,
        trigger="falsification_objection",
        depth=depth,
    )
    return revised, cost
