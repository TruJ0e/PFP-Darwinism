"""
v0.47 — Evolving Exploration Briefs (Truman's Design).

Tests for:
1. Model-generated briefs: problem-agnostic, generated at runtime.
2. Coverage by construction: starters generated against each other, final brief forced
   toward what nobody is looking at.
3. Brief mutations: descendants receive revised briefs on forks and when surviving
   falsifications with objections.
4. Selection acts on framings: brief lineage is journaled in the hash-chained feed
   (spawn events carry brief, brief_id, parent_brief_id).
5. Integration: probes and conclusions receive problem + brief + parent reasoning.
6. Escape dial: --no-briefs / enable_briefs=False matches v0.46 behavior exactly.
7. Determinism: repeated mock runs produce identical briefs, spend, and outcomes.
"""

from __future__ import annotations

from pfp import (
    ExplorationBrief,
    MainHarness,
    MockOpenAIClient,
    compute_brief_id,
    generate_starter_briefs,
    mutate_brief_for_fork,
)


PROBLEM = "A small business's SSH works laptop->desktop but not desktop->laptop. Diagnose the root causes and verify the solution."
ALT_PROBLEM = "Database transactions deadlock intermittently under peak load. Diagnose the root causes and verify the fix."


def test_starter_briefs_are_model_generated_and_distinct():
    """1 & 2: Starters receive distinct briefs generated by the client, final brief is orthogonal."""
    client = MockOpenAIClient()
    briefs, costs = generate_starter_briefs(client, PROBLEM, count=3)
    assert len(briefs) == 3
    assert len(costs) == 3
    assert all(c > 0 for c in costs)

    # All briefs must have non-empty text and content-addressed IDs
    for b in briefs:
        assert b.brief.strip()
        assert b.brief_id.startswith("brief_")
        assert b.parent_brief_id is None
        assert b.trigger == "starter"

    # All 3 briefs must be distinct from each other
    brief_texts = [b.brief for b in briefs]
    assert len(set(brief_texts)) == 3

    # Final brief is forced toward what nobody is looking at
    final_brief = briefs[-1]
    assert any(w in final_brief.brief.lower() for w in ("unconventional", "nobody", "orthogonal", "anomalies"))


def test_coverage_by_construction_scales_to_many_starters():
    """2: 9 starters all receive distinct hypothesis regions, final brief forced toward orthogonal."""
    client = MockOpenAIClient()
    briefs, _ = generate_starter_briefs(client, PROBLEM, count=9)
    assert len(briefs) == 9
    brief_ids = [b.brief_id for b in briefs]
    # At least 8 distinct brief IDs (8 categories + final orthogonal)
    assert len(set(brief_ids)) >= 8
    assert briefs[-1].brief != briefs[0].brief


def test_brief_mutation_on_fork_carries_parent_brief_id():
    """3a: Children spawned at a fork receive revised brief variations carrying parent brief ID."""
    client = MockOpenAIClient()
    parent_brief = ExplorationBrief(
        brief_id=compute_brief_id("Investigate process lifecycle and runtime daemon execution."),
        brief="Investigate process lifecycle and runtime daemon execution.",
        trigger="starter",
    )

    child_1, cost_1 = mutate_brief_for_fork(
        client=client,
        problem=PROBLEM,
        parent_brief=parent_brief,
        fork_description="Restart service and check systemd journal",
        fork_reasoning="Daemon may be hung or inactive",
        prior_sibling_briefs=[],
        depth=1,
    )
    assert child_1.parent_brief_id == parent_brief.brief_id
    assert child_1.trigger == "fork_variation"
    assert child_1.depth == 1
    assert cost_1 > 0

    child_2, cost_2 = mutate_brief_for_fork(
        client=client,
        problem=PROBLEM,
        parent_brief=parent_brief,
        fork_description="Check socket binding and listen backlog",
        fork_reasoning="Process may be failing to accept connections",
        prior_sibling_briefs=[child_1],
        is_final=True,
        depth=1,
    )
    assert child_2.parent_brief_id == parent_brief.brief_id
    assert child_2.brief_id != child_1.brief_id


def test_survived_falsification_objection_feeds_descendant_brief():
    """3b: An objection survived during falsification feeds into descendant brief mutation."""
    client = MockOpenAIClient()
    parent_brief = ExplorationBrief(
        brief_id=compute_brief_id("Check boundary filtering and firewall rules."),
        brief="Check boundary filtering and firewall rules.",
        trigger="starter",
    )
    objection = "Attack exposed: does not account for stateful connection tracking timeouts."

    mutated, cost = mutate_brief_for_fork(
        client=client,
        problem=PROBLEM,
        parent_brief=parent_brief,
        fork_description="Audit connection tracking table limits",
        fork_reasoning="Stateful return traffic may be dropped if conntrack table overflows",
        survived_objection=objection,
        depth=1,
    )
    assert mutated.parent_brief_id == parent_brief.brief_id
    assert mutated.trigger == "falsification_objection"
    assert cost > 0
    assert "objection" in mutated.brief.lower() or "exposed" in mutated.brief.lower() or "falsification" in mutated.brief.lower()


def test_brief_lineage_is_journaled_in_spawn_events():
    """4: Spawn events in the hash-chained feed carry brief, brief_id, and parent_brief_id."""
    harness = MainHarness(
        client=MockOpenAIClient(),
        starter_agents=3,
        hard_cap_usd=2.0,
        enable_briefs=True,
        enable_selection=True,
        test_before_merge=False,
    )
    harness.run(PROBLEM)
    events = harness.arena_feed.events

    spawn_events = [e for e in events if e.event_type == "spawn"]
    assert len(spawn_events) >= 3

    # Starters carry root briefs
    starter_spawns = [e for e in spawn_events if e.snapshot.get("parent") is None]
    for e in starter_spawns:
        assert "brief" in e.details
        assert "brief_id" in e.details
        assert e.details.get("parent_brief_id") is None
        assert e.details["brief_id"].startswith("brief_")

    # Descendants carry parent_brief_id matching ancestor brief
    child_spawns = [e for e in spawn_events if e.snapshot.get("parent") is not None and "brief" in e.details]
    assert len(child_spawns) > 0
    for e in child_spawns:
        assert e.details.get("parent_brief_id") is not None

    # The journal hash chain must verify
    assert harness.arena_feed.anchor()["verified_chain"] is True


def test_no_briefs_escape_dial_matches_v046():
    """Escape dial: when enable_briefs=False, behavior matches v0.46 exactly."""
    harness_briefs = MainHarness(
        client=MockOpenAIClient(),
        starter_agents=3,
        hard_cap_usd=2.0,
        enable_briefs=True,
        enable_selection=True,
        test_before_merge=False,
    )
    harness_nobriefs = MainHarness(
        client=MockOpenAIClient(),
        starter_agents=3,
        hard_cap_usd=2.0,
        enable_briefs=False,
        enable_selection=True,
        test_before_merge=False,
    )
    s_briefs = harness_briefs.run(PROBLEM)
    s_nobriefs = harness_nobriefs.run(PROBLEM)

    # When no-briefs is set:
    # 1. Starters carry no brief in directive or spawn details
    for starter in harness_nobriefs.starters:
        assert starter.directive.brief == ""
        assert starter.directive.brief_id == ""

    nobriefs_spawns = [e for e in harness_nobriefs.arena_feed.events if e.event_type == "spawn"]
    for e in nobriefs_spawns:
        assert "brief" not in e.details

    # 2. Spend and branch count match v0.46 baseline (37 branches, $0.8667 arena spend over 154 calls)
    assert s_nobriefs["total_branches_spawned"] == 37
    assert s_nobriefs["budget"]["total_spent_usd"] == 0.865732
    assert s_nobriefs["budget"]["api_calls"] == 154
    assert len(harness_nobriefs.arena_feed.events) == 261

    # Briefs run should have generated brief calls and different spend/events
    assert s_briefs["budget"]["api_calls"] > s_nobriefs["budget"]["api_calls"]
    assert len(harness_briefs.arena_feed.events) > len(harness_nobriefs.arena_feed.events)


def test_mock_brief_runs_are_deterministic_and_reproducible():
    """Determinism: repeated mock runs with briefs produce identical briefs, spend, and outcomes."""
    outcomes = []
    for _ in range(3):
        harness = MainHarness(
            client=MockOpenAIClient(),
            starter_agents=3,
            hard_cap_usd=2.0,
            enable_briefs=True,
            enable_selection=True,
        test_before_merge=False,
        )
        summary = harness.run(PROBLEM)
        starter_bids = [s.directive.brief_id for s in harness.starters]
        outcomes.append((
            starter_bids,
            summary["budget"]["total_spent_usd"],
            summary["total_branches_spawned"],
            summary["budget"]["api_calls"],
            sorted(e.details.get("brief_id") for e in harness.arena_feed.events if e.event_type == "spawn"),
        ))

    assert outcomes[0] == outcomes[1] == outcomes[2]
